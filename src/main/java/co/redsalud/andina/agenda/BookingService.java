package co.redsalud.andina.agenda;

import java.util.UUID;

import org.springframework.context.ApplicationEventPublisher;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import co.redsalud.andina.agenda.internal.Booking;
import co.redsalud.andina.agenda.internal.BookingRepository;
import co.redsalud.andina.agenda.internal.Slot;
import co.redsalud.andina.agenda.internal.SlotRepository;
import lombok.RequiredArgsConstructor;

@Service
@RequiredArgsConstructor
public class BookingService {

	private final SlotRepository slotRepository;
	private final BookingRepository bookingRepository;
	private final ApplicationEventPublisher events;

	/**
	 * Idempotent on {@code bookingId} (generated by the client): a retry of the same request returns the same booking.
	 * A taken slot is rejected with a conflict; the unique constraint on slot_id decides concurrent attempts.
	 */
	@PreAuthorize("hasRole('RURAL_DOCTOR') or (hasRole('PATIENT') and authentication.name == #patientId.toString())")
	@Transactional
	public BookingView book(UUID bookingId, UUID slotId, UUID patientId, UUID bookedBy) {
		var existing = bookingRepository.findById(bookingId);
		if (existing.isPresent()) {
			if (existing.get().sameRequestAs(slotId, patientId)) {
				return BookingView.of(existing.get(), slotRepository.findById(slotId).orElseThrow());
			}
			throw new AgendaConflictException("Booking id " + bookingId + " was already used for a different request");
		}
		Slot slot = slotRepository.findById(slotId).orElseThrow(() -> new SlotNotFoundException(slotId));
		try {
			Booking booking = bookingRepository.saveAndFlush(new Booking(bookingId, slotId, patientId, bookedBy));
			events.publishEvent(new SlotBooked(bookingId, slotId, slot.getSpecialistId(), patientId, slot.getStartAt()));
			return BookingView.of(booking, slot);
		} catch (DataIntegrityViolationException e) {
			throw new AgendaConflictException("Slot " + slotId + " is already booked");
		}
	}
}
